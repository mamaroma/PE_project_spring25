def рассчитать_имт(вес, рост):
    """Рассчитывает индекс массы тела (ИМТ)."""
    return вес / ((рост / 100) ** 2)


def рассчитать_нагрузку(возраст, здоровье, дистанция, повторения, гибкость, цель, вес, рост, стресс, сон, опыт,
                        предпочтения, среда):
    """
    Рассчитывает тренировочную нагрузку с учетом множества параметров.
    """
    # Коэффициент здоровья
    здоровье_коэффициент = {
        'здоров': 1.0,
        'небольшие_ограничения': 0.8,
        'хронические_болезни': 0.6,
        'серьезные_ограничения': 0.4
    }
    H = здоровье_коэффициент.get(здоровье, 1.0)

    # Уровень физической подготовки с минимальным порогом
    P1 = min(дистанция / 600, 1.0)
    P2 = min(повторения / 20, 1.0)
    P3 = min(гибкость / 20, 1.0)
    P = (P1 + P2 + P3) / 3
    P = max(P, 0.3)  # Минимальный порог для физической подготовленности

    # Корректировка по ИМТ
    имт = рассчитать_имт(вес, рост)
    имт_коэффициент = 1.0
    if имт > 30:
        имт_коэффициент = 0.8
    elif имт < 18.5:
        имт_коэффициент = 0.9

    # Корректировка по стрессу
    стресс_коэффициент = {'низкий': 1.0, 'средний': 0.9, 'высокий': 0.7}
    S = стресс_коэффициент.get(стресс, 1.0)

    # Корректировка по сну
    сон_коэффициент = 1.0 if сон >= 7 else 0.8 if сон >= 5 else 0.6

    # Корректировка по опыту
    опыт_коэффициент = {'новичок': 0.7, 'любитель': 1.0, 'продвинутый': 1.2}
    E = опыт_коэффициент.get(опыт, 1.0)

    # Интенсивность в зависимости от цели
    интенсивность_коэффициент = {
        'выносливость': 0.7,
        'сила': 0.6,
        'гибкость': 0.45,
        'снижение_веса': 0.65,
        'релаксация': 0.4
    }
    I = интенсивность_коэффициент.get(цель, 0.7)

    # Базовое время тренировки
    T = 60 if H >= 0.8 else 40  # Увеличено для людей с ограничениями

    # Итоговая нагрузка с минимальным порогом
    нагрузка = H * P * T * I * имт_коэффициент * S * сон_коэффициент * E
    нагрузка = max(нагрузка, 15)  # Минимальная длительность 15 минут
    нагрузка = min(нагрузка, 90)  # Ограничение до 90 минут

    # Целевой пульс
    максимальный_пульс = 220 - возраст
    целевой_пульс = f"{int(I * максимальный_пульс * 0.9)}–{int(I * максимальный_пульс)} уд/мин"

    # Диагностика низкой нагрузки
    диагностика = []
    if H <= 0.6:
        диагностика.append(f"Низкий коэффициент здоровья ({H}): у вас есть ограничения по здоровью.")
    if P <= 0.3:
        диагностика.append(f"Низкий уровень физической подготовки ({P}): результаты теста низкие.")
    if S <= 0.7:
        диагностика.append(f"Высокий уровень стресса ({S}): это снижает нагрузку.")
    if сон_коэффициент <= 0.6:
        диагностика.append(f"Недостаток сна ({сон} часов, коэффициент {сон_коэффициент}): это снижает нагрузку.")

    # Создание программы
    программа = составить_программу(нагрузка, I, H, цель, предпочтения, среда, опыт)

    return {
        'длительность': round(нагрузка, 1),
        'интенсивность': целевой_пульс,
        'программа': программа,
        'имт': round(имт, 1),
        'диагностика': диагностика
    }


def составить_программу(нагрузка, интенсивность, здоровье_коэф, цель, предпочтения, среда, опыт):
    """Составляет индивидуальную программу тренировок."""
    программа = []

    # Разминка
    разминка_длительность = 5 if нагрузка < 30 else 10
    разминка = f"Разминка ({разминка_длительность} мин): Легкая ходьба, дыхательные упражнения, суставная гимнастика"
    программа.append(разминка)

    # Основная часть
    основная_длительность = int(нагрузка - разминка_длительность - 5)  # 5 мин на заминку
    доступные_активности = выбрать_активности(здоровье_коэф, цель, предпочтения, среда, опыт)

    if здоровье_коэф <= 0.4:
        программа.append(
            f"Основная часть ({основная_длительность} мин): Лечебная физкультура (пассивная растяжка, дыхательные упражнения, легкие прогулки)")
    elif здоровье_коэф <= 0.6:
        программа.append(
            f"Основная часть ({основная_длительность} мин): {доступные_активности[0]} (например, аквааэробика, растяжка или легкая ходьба)")
    else:
        программа.append(
            f"Основная часть ({основная_длительность} мин): {доступные_активности[0]} с интенсивностью {int(интенсивность * 100)}% от максимального пульса")
        if len(доступные_активности) > 1 and основная_длительность >= 20:
            программа.append(f"Дополнительно ({основная_длительность // 2} мин): {доступные_активности[1]}")

    # Заминка
    заминка = "Заминка (5 мин): Медленная ходьба, дыхательные упражнения, легкая растяжка"
    программа.append(заминка)

    return программа


def выбрать_активности(здоровье_коэф, цель, предпочтения, среда, опыт):
    """Выбирает подходящие виды активности с учетом параметров."""
    активности = []

    if здоровье_коэф <= 0.4:
        активности = ["Лечебная физкультура", "Пассивная растяжка", "Дыхательные упражнения"]
    elif здоровье_коэф <= 0.6:
        активности = ["Аквааэробика", "Легкая ходьба", "Растяжка", "Йога для начинающих"]
        if 'бассейн' in среда:
            активности.append("Легкое плавание")
    elif здоровье_коэф <= 0.8:
        активности = ["Свободная ходьба", "Йога", "Пилатес", "Велотренажер", "Легкий бег"]
        if 'бассейн' in среда:
            активности.append("Плавание")
        if 'тренажерный_зал' in среда:
            активности.append("Легкие силовые тренировки")
    else:
        активности = ["Бег", "Плавание", "Велоспорт", "Силовые тренировки", "Теннис", "Танцы"]
        if 'парк' in среда:
            активности.append("Скандинавская ходьба")
        if 'дом' in среда:
            активности.append("Функциональные тренировки дома")

    if цель == 'снижение_веса':
        активности.insert(0, "Аэробные упражнения (ходьба, плавание, велоспорт)")
    elif цель == 'релаксация':
        активности.insert(0, "Йога или дыхательные практики")

    отобранные = [акт for акт in активности if any(п in акт.lower() for п in предпочтения)]
    отобранные.extend([акт for акт in активности if акт not in отобранные])

    if опыт == 'новичок' and any('силовые' in акт.lower() or 'бег' in акт.lower() for акт in отобранные):
        отобранные = [f"Легкая {акт}" if 'силовые' in акт.lower() or 'бег' in акт.lower() else акт for акт in
                      отобранные]

    return отобранные[:2]


